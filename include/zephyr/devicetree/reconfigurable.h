#ifndef ZEPHYR_INCLUDE_DEVICETREE_RECONFIGURABLE_H_
#define ZEPHYR_INCLUDE_DEVICETREE_RECONFIGURABLE_H_

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include <zephyr/devicetree.h>
#include <zephyr/sys/iterable_sections.h>
#include <zephyr/sys/util.h>

/**
 * @brief Runtime-reconfigurable devicetree resources
 * @defgroup devicetree-reconfigurable Reconfigurable devicetree resources
 * @ingroup devicetree
 * @{
 *
 * Support for hardware whose register base/size or interrupt may change at
 * runtime (for example FPGA dynamic-function-exchange soft-IP), without a
 * runtime flattened devicetree (FDT) blob on the target.
 *
 * A node marked with the ``zephyr,reconfigurable`` property gets a mutable
 * descriptor (in RAM) seeded from its devicetree ``reg``/``interrupts``. The
 * descriptor can be patched at runtime from a manifest before the owning device
 * is (re)initialized; reconfigurable drivers read their resources from the
 * descriptor instead of from the compile-time ``DT_REG_ADDR()`` constants.
 */

/**
 * @brief Mutable descriptor for a runtime-reconfigurable node.
 *
 * Seeded from devicetree at build time; fields may be patched at runtime.
 */
struct dt_reconfigurable {
	/** Node full name, for debug and lookup. */
	const char *name;
	/** Devicetree dependency ordinal; stable identifier for the node. */
	int ord;
	/** Current register base address (seeded from DT ``reg``). */
	uintptr_t reg_addr;
	/** Current register region size (seeded from DT ``reg``). */
	size_t reg_size;
	/** Current interrupt number (seeded from DT, or -1 if none). */
	int32_t irq;
	/** Whether the hardware is currently present/active. */
	bool present;
};

/** @cond INTERNAL_HIDDEN */
#define Z_DT_RECONF_IRQ(node_id)                                                                   \
	COND_CODE_1(DT_IRQ_HAS_IDX(node_id, 0), (DT_IRQN(node_id)), (-1))
#define Z_DT_RECONF_REG_ADDR(node_id)                                                              \
	COND_CODE_1(DT_REG_HAS_IDX(node_id, 0), (DT_REG_ADDR(node_id)), (0))
#define Z_DT_RECONF_REG_SIZE(node_id)                                                              \
	COND_CODE_1(DT_REG_HAS_IDX(node_id, 0), (DT_REG_SIZE(node_id)), (0))
/** @endcond */

/**
 * @brief Define a mutable reconfigurable descriptor for a devicetree node.
 *
 * Places a ::dt_reconfigurable entry into the iterable ``dt_reconfigurable``
 * section (RAM), seeded from the node's ``reg`` and first ``interrupts`` entry.
 * The node must have the ``zephyr,reconfigurable`` property.
 *
 * @param node_id Devicetree node identifier.
 */
#define DT_RECONFIGURABLE_DEFINE(node_id)                                                         \
	BUILD_ASSERT(DT_PROP(node_id, zephyr_reconfigurable),                                      \
		     "node is missing the zephyr,reconfigurable property");                       \
	STRUCT_SECTION_ITERABLE(dt_reconfigurable,                                                 \
				_CONCAT(dt_reconfigurable_, DT_DEP_ORD(node_id))) = {              \
		.name = DT_NODE_FULL_NAME(node_id),                                               \
		.ord = DT_DEP_ORD(node_id),                                                       \
		.reg_addr = (uintptr_t)Z_DT_RECONF_REG_ADDR(node_id),                             \
		.reg_size = (size_t)Z_DT_RECONF_REG_SIZE(node_id),                                \
		.irq = (int32_t)Z_DT_RECONF_IRQ(node_id),                                         \
		.present = DT_NODE_HAS_STATUS(node_id, okay),                                     \
	}

/**
 * @brief Like DT_RECONFIGURABLE_DEFINE(), but for a ``DT_DRV_COMPAT`` instance.
 *
 * @param inst Instance number.
 */
#define DT_RECONFIGURABLE_INST_DEFINE(inst) DT_RECONFIGURABLE_DEFINE(DT_DRV_INST(inst))

/** A single entry of a runtime manifest (e.g. generated by Lopper per segment). */
struct dt_reconfigurable_manifest_entry {
	/** Target node dependency ordinal (see ::dt_reconfigurable.ord). */
	int ord;
	/** New register base address. */
	uintptr_t reg_addr;
	/** New register region size. */
	size_t reg_size;
	/** New interrupt number, or -1 for none. */
	int32_t irq;
	/** New present/active state. */
	bool present;
};

/**
 * @brief Look up a reconfigurable descriptor by dependency ordinal.
 *
 * @param ord Node dependency ordinal (``DT_DEP_ORD()``).
 * @return Pointer to the mutable descriptor, or NULL if not found.
 */
struct dt_reconfigurable *dt_reconfigurable_get(int ord);

/**
 * @brief Patch a reconfigurable descriptor's resources.
 *
 * @param ord Node dependency ordinal.
 * @param reg_addr New register base address.
 * @param reg_size New register region size.
 * @param irq New interrupt number, or -1 for none.
 * @retval 0 on success.
 * @retval -ENOENT if no descriptor with @p ord exists.
 */
int dt_reconfigurable_patch(int ord, uintptr_t reg_addr, size_t reg_size, int32_t irq);

/**
 * @brief Set a reconfigurable node's present/active state.
 *
 * @param ord Node dependency ordinal.
 * @param present New present state.
 * @retval 0 on success.
 * @retval -ENOENT if no descriptor with @p ord exists.
 */
int dt_reconfigurable_set_present(int ord, bool present);

/**
 * @brief Number of reconfigurable descriptors defined in the image.
 *
 * @return Descriptor count.
 */
size_t dt_reconfigurable_count(void);

/**
 * @brief Iterate over all reconfigurable descriptors.
 *
 * Iteration stops early if @p cb returns non-zero, and that value is returned.
 *
 * @param cb Callback invoked per descriptor.
 * @param user Opaque pointer passed to @p cb.
 * @return 0 when all descriptors were visited, or the first non-zero @p cb result.
 */
int dt_reconfigurable_foreach(int (*cb)(struct dt_reconfigurable *desc, void *user), void *user);

/**
 * @brief Apply a manifest to the reconfigurable descriptor table.
 *
 * Each entry patches the matching descriptor (by ordinal) and its present state.
 * Intended to be called between device_deinit() and device_init() on a segment
 * switch, with a manifest generated offline (e.g. by Lopper).
 *
 * @param m Manifest entries.
 * @param n Number of entries.
 * @retval 0 on success.
 * @retval -ENOENT if any entry references an unknown ordinal (remaining entries
 *         are still applied).
 * @retval -EINVAL if @p m is NULL and @p n is non-zero.
 */
int dt_reconfigurable_apply(const struct dt_reconfigurable_manifest_entry *m, size_t n);

/** @} */

#endif /* ZEPHYR_INCLUDE_DEVICETREE_RECONFIGURABLE_H_ */
